"""Build the SDK dictionary text from package sources and an OpenCode spec. Pure: no disk, no network."""

from __future__ import annotations

from workbench.export_grouper import ExportGrouper
from workbench.opencode_endpoint_reader import OpencodeEndpointReader
from workbench.sdk_surface_reader import ClassSurface, FunctionSurface, SdkSourceReader
from workbench.surface_markdown_writer import SurfaceMarkdownWriter

_CENTRAL_CLASSES = ("ClaudeAgentOptions", "ClaudeSDKClient")
_COMPACT_GROUPS = ("Messages", "Content blocks", "Hooks", "Permissions")


class SdkDictionaryBuilder:
    """Render the Claude SDK dictionary and the OpenCode endpoint dictionary."""

    def __init__(self, reader: SdkSourceReader, writer: SurfaceMarkdownWriter,
                 grouper: ExportGrouper, endpoint_reader: OpencodeEndpointReader) -> None:
        self._reader, self._writer = reader, writer
        self._grouper, self._endpoint_reader = grouper, endpoint_reader

    def build_claude(self, versions: str, init_source: str, module_sources: tuple[str, ...]) -> str:
        exports = self._reader.read_exports(init_source)
        classes, functions = self._collect(module_sources)
        groups = self._grouper.group(exports)
        parts = [f"# Claude Agent SDK dictionary\n\n{versions}\n\nGenerated from the package source by `scripts/sdk_surfaces.py`. Do not edit by hand.",
                 self._group_map(groups), self._central(classes), self._function_section(exports, functions),
                 self._compact_section(groups, classes)]
        return "\n\n".join(parts) + "\n"

    def build_opencode(self, spec: dict) -> str:
        groups = self._endpoint_reader.read(spec)
        total = sum(len(endpoints) for endpoints in groups.values())
        parts = [f"# OpenCode server dictionary\n\n{total} operations in {len(groups)} groups, read from the OpenAPI spec of OpenCode 2 (`opencode api --standalone GET /openapi.json`). Generated by `scripts/sdk_surfaces.py`. Do not edit by hand."]
        for name, endpoints in groups.items():
            parts.append(f"## /{name}\n\n{self._writer.endpoints_table(endpoints)}")
        return "\n\n".join(parts) + "\n"

    def _collect(self, sources: tuple[str, ...]) -> tuple[dict[str, ClassSurface], dict[str, FunctionSurface]]:
        classes: dict[str, ClassSurface] = {}
        functions: dict[str, FunctionSurface] = {}
        for source in sources:
            surface = self._reader.read(source)
            classes.update({c.name: c for c in surface.classes})
            functions.update({f.name: f for f in surface.functions})
        return classes, functions

    def _group_map(self, groups: dict[str, tuple[str, ...]]) -> str:
        lines = [f"## Map: every exported name by group\n"]
        lines += [f"- **{title}** ({len(names)}): " + ", ".join(f"`{n}`" for n in names) for title, names in groups.items()]
        return "\n".join(lines)

    def _central(self, classes: dict[str, ClassSurface]) -> str:
        sections = [self._writer.class_section(classes[name]) for name in _CENTRAL_CLASSES if name in classes]
        return "## The two central classes\n\n" + "\n\n".join(sections)

    def _function_section(self, exports: tuple[str, ...], functions: dict[str, FunctionSurface]) -> str:
        exported = tuple(functions[name] for name in exports if name in functions)
        return "## Exported functions\n\n" + self._writer.functions_table(exported)

    def _compact_section(self, groups: dict[str, tuple[str, ...]], classes: dict[str, ClassSurface]) -> str:
        parts = ["## Types by group (fields in brackets)"]
        for title, names in groups.items():
            if not title.startswith(_COMPACT_GROUPS):
                continue
            lines = [f"### {title}"]
            for name in names:
                surface = classes.get(name)
                if surface is not None:
                    fields = ", ".join(f.name for f in surface.fields)
                    lines.append(f"- `{name}` [{fields}] {surface.doc}".rstrip())
            parts.append("\n".join(lines))
        return "\n\n".join(parts)
